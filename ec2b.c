static const unsigned char ec2bXorKey[16] = {0xa2, 0x25, 0x25, 0x99, 0xb7, 0x62, 0xf4, 0x39, 0x28, 0xe1, 0xb7, 0x73, 0x91, 0x05, 0x25, 0x87};

void xorKeyFromEc2b(const ec2b_t* in, uint8_t* out) {
	uint8_t _key[16];
	memcpy(_key, in->key, 16);
	aesScrambleKey(_key, ec2bAesRoundKeys);
	xorCrypt(_key, 16, ec2bXorKey, 16);
	const uint64_t* key = (const uint64_t*) _key;
	const uint64_t* data = (const uint64_t*) in->data;
	uint64_t seed = ~0xceac3b5a867837ac;
	seed ^= key[0];
	seed ^= key[1];
	unsigned int i;
	for (i = 0; i < 256; i++) {
		seed ^= data[i];
	}
	fprintf(stderr, "ec2b seed 0x%016lx\n", seed);
	genXorpadFromSeed(seed, out, 4096, 0, 0);
}

void genNewEc2b(ec2b_t* out, uint8_t* key, uint8_t* data, uint64_t* seed, unsigned int getNewSeed) {
	out->magic = htobe32(0x45633262);
	out->keySz = htole32(16);
	out->dataSz = htole32(2048);
	uint64_t newSeed;
	uint8_t* newKey = out->key;
	uint8_t* newData = out->data;
	uint64_t* _key = (uint64_t*) newKey;
	uint64_t* _data = (uint64_t*) newData;
	unsigned int i;
	if (key != NULL) {
		memcpy(newKey, key, 16);
		aesScrambleKey(newKey, ec2bAesRoundKeys);
		xorCrypt(newKey, 16, ec2bXorKey, 16);
	}
	else {
		getrandom(newKey, 16, 0);
	}
	if (data != NULL) {
		memcpy(newData, data, 2048);
	}
	else {
		getrandom(newData, 2048, 0);
	}
	if (seed != NULL) {
		if (getNewSeed) {
			newSeed = ~0xceac3b5a867837ac;
			newSeed ^= _key[0];
			newSeed ^= _key[1];
			for (i = 0; i < 256; i++) {
				newSeed ^= _data[i];
			}
			*seed = newSeed;
		}
		else {
			newSeed = ~0;
			for (i = 0; i < 256; i++) {
				newSeed ^= _data[i];
			}
			newSeed ^= *seed;
			newSeed ^= _key[1];
			newSeed ^= 0xceac3b5a867837ac;
			_key[0] = newSeed;
		}
	}
	xorCrypt(newKey, 16, ec2bXorKey, 16);
	aesUnscrambleKey(newKey, ec2bAesRoundKeys);
}
