static void blkScrambleKey(uint8_t* key) {
	unsigned int i;
	unsigned int idx;
	for (i = 0; i < 16; i++) {
		idx = ((i & 3) << 8) | key[i];
		key[i] = blkScrambleTbl[idx];
	}
}

static void blkUnscrambleKey(uint8_t* key) {
	unsigned int i, j;
	unsigned int val;
	for (i = 0; i < 16; i++) {
		for (j = 0; j < 256; j++) {
			val = blkScrambleTbl[((i & 3) << 8) | j];
			if (val == key[i]) {
				key[i] = j;
				break;
			}
		}
	}
}

