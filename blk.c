static uint8_t xorpad[4096];

void decrypt_blk0(uint8_t* buf, size_t sz, size_t seedSz, uint8_t* key, uint64_t* _seed, uint8_t* _out) {
	uint8_t* out = xorpad;
	if (_out != NULL) out = _out;
	blkScrambleKey(key);
	aesScrambleKeyMhy(key, blkAesRoundKeys);
	xorCrypt(key, 16, blkXorKey, 16);
	uint64_t seed = ~0x567ba22babb08098;
	uint64_t* _buf = (uint64_t*) buf;
	const uint64_t* _key = (const uint64_t*) key;
	size_t _sz = (seedSz <= 4096) ? seedSz : 4096;
	unsigned int i;
	for (i = 0; i < (_sz / sizeof(uint64_t)); i++) {
		seed ^= le64toh(_buf[i]);
	}
	seed ^= le64toh(_key[0]);
	seed ^= le64toh(_key[1]);
	if (_seed != NULL) *_seed = seed;
	genXorpadFromSeed(seed, out, 4096, 0, 0);
	xorCrypt(buf, sz, out, 4096);
}

void encrypt_blk0(uint8_t* buf, size_t sz, size_t seedSz, uint8_t* key, uint64_t seed) {
	genXorpadFromSeed(seed, xorpad, 4096, 0, 0);
	xorCrypt(buf, sz, xorpad, 4096);
	uint64_t* _buf = (uint64_t*) buf;
	uint64_t* _key = (uint64_t*) key;
	uint64_t _seed = ~0;
	size_t _sz = (seedSz <= 4096) ? seedSz : 4096;
	unsigned int i;
	for (i = 0; i < (_sz / sizeof(uint64_t)); i++) {
		_seed ^= le64toh(_buf[i]);
	}
	_seed ^= 0x567ba22babb08098;
	_seed ^= le64toh(_key[1]);
	_seed ^= seed;
	_key[0] = htole64(_seed);
	xorCrypt(key, 16, blkXorKey, 16);
	aesUnscrambleKeyMhy(key, blkAesRoundKeys);
	blkUnscrambleKey(key);
}
